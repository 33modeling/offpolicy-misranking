def x1_tables(tau, items):
    rows, out = [], {}
    by = {}
    for it in sorted(items, key=lambda i: not str(i["key"]).endswith(".train")):  # eval items override train items
        if it.get("arm") and it.get("seed") is not None:
            if str(it["key"]).endswith(".train"):
                it = dict(it, state="pending", reason=it.get("reason") or "V9 training not finished")
            by.setdefault(it["cohort"], {}).setdefault(it["arm"], {})[it["seed"]] = it
    for cohort in env.X1_COHORTS:
        arms = by.get(cohort, {})
        seeds = [5, 6, 7, 8, 9]
        vals = {a: {s: (arms.get(a, {}).get(s) or {}).get("value") if (arms.get(a, {}).get(s) or {}).get("state") == "done"
                    else None for s in seeds} for a in ("staged", "sr", "alignment", "random")}
        for a in vals:
            for s in seeds:
                it = arms.get(a, {}).get(s)
                rows.append({"cohort": cohort, "seed": s, "arm": a, "reward_fraction": vals[a][s],
                             "status": "measured" if vals[a][s] is not None else "pending",
                             "reason": None if vals[a][s] is not None else (it or {}).get("reason") or "not measured yet"})
        complete = {a: all(v is not None for v in vals[a].values()) for a in vals}
        means = {a: mean(vals[a].values()) if complete[a] else None for a in vals}
        best = None
        if complete["sr"] and complete["alignment"]:
            best = "sr" if means["sr"] >= means["alignment"] else "alignment"
        out[cohort] = {
            "seeds": seeds, "means": means, "complete": complete, "best_arm": best,
            "best_rule": "the single-selector arm (SR or Alignment) with the higher seed mean in this cohort",
            "staged_minus_sr": contrast(vals["staged"], vals["sr"], seeds, "Staged - SR"),
            "staged_minus_alignment": contrast(vals["staged"], vals["alignment"], seeds, "Staged - Alignment"),
            "staged_minus_random": contrast(vals["staged"], vals["random"], seeds, "Staged - Random"),
            "staged_minus_best": contrast(vals["staged"], vals[best], seeds, f"Staged - best ({best})") if best else
            {"status": "pending", "n_training_seeds": 0, "reason": "best arm needs SR and Alignment on every seed"},
            "per_seed": vals}
    lines = [PREAMBLE, f"% X1: Random vs Staged(tau={tau}) vs SR vs Alignment at update 275; mean reward (\\%), "
             "paired difference in pp [95\\% paired-t CI] (wins/ties/losses over seeds 5--9)",
             "\\begin{tabular}{lrrrrllll}", "\\toprule",
             "Cohort & Random & Staged & SR & Alignment & Staged$-$SR & Staged$-$Alignment & Staged$-$best & "
             "Staged$-$Random \\\\", "\\midrule"]
    for cohort in env.X1_COHORTS:
        o = out[cohort]
        lines.append(f"{NAMES[cohort]} & {fmt_pct(pct(o['means']['random']), 'X1')} & "
                     f"{fmt_pct(pct(o['means']['staged']), 'X1')} & {fmt_pct(pct(o['means']['sr']), 'X1')} & "
                     f"{fmt_pct(pct(o['means']['alignment']), 'X1')} & {fmt_delta(o['staged_minus_sr'], 'X1')} & "
                     f"{fmt_delta(o['staged_minus_alignment'], 'X1')} & {fmt_delta(o['staged_minus_best'], 'X1')} & "
                     f"{fmt_delta(o['staged_minus_random'], 'X1')} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return out, rows, "\n".join(lines)


# ------------------------------------------------------------------ tau sweep
def tau_table(rec):
    taus = rec["candidate_taus"]
    lines = [PREAMBLE, f"% tau sweep, OLMo MATH Branch Bank seeds 5--9 (development cohort). Rule: {rec['rule']}",
             "\\begin{tabular}{l" + "r" * len(taus) + "}", "\\toprule",
             "$\\tau$ & " + " & ".join(str(t) for t in taus) + " \\\\", "\\midrule"]
    for basis, means in ((rec["basis"], rec["mean_reward_fraction_by_tau"]), (rec["other_basis"], rec["other_basis_means"])):
        cells = []
        for t in taus:
            v = None if means is None else means.get(str(t))
            cell = fmt_pct(pct(v), "P0")
            if basis == rec["basis"] and t == rec["tau"]:
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        label = {"equal_budget": "equal budget (V8 $B$)", "matched_update": "matched update 275"}[basis]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", f"% selected tau = {rec['tau']} (basis {rec['basis']})", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ X2
def x2_tables(x1, items):
    out = {}
    lines = [PREAMBLE, "% X2: equal compute. B = mean continuation cost of Staged (trajectory to tau + SR branch to 275). "
             "SR (and earlier switches) extended past 275 until B; Alignment stopped at its last snapshot within B.",
             "\\begin{tabular}{llrrr}", "\\toprule",
             "Cohort & Arm & Reward (\\%) & Mean update & Mean cost (GPU-h) \\\\", "\\midrule"]
    for cohort in env.X2_COHORTS:
        its = [i for i in items if i["cohort"] == cohort]
        B = next((i.get("value") for i in its if i["key"] == "budget" and i["state"] == "done"), None)
        seeds = [5, 6, 7, 8, 9]
        arms = {}
        for i in its:
            if i.get("arm") and "@B" in i["key"] and not i["key"].endswith(".train"):
                arms.setdefault(i["arm"], {})[i["seed"]] = i
        staged275 = x1.get(cohort, {}).get("per_seed", {}).get("staged", {s: None for s in seeds})
        res = {"budget_gpu_seconds": B, "arms": {}}
        for arm, by in sorted(arms.items()):
            vals = {s: by[s].get("value") if s in by and by[s]["state"] == "done" else None for s in seeds}
            done = all(v is not None for v in vals.values())
            ups = [by[s].get("endpoint_update") for s in seeds if s in by]
            costs = [by[s].get("cost") for s in seeds if s in by]
            res["arms"][arm] = {"per_seed": vals, "mean": mean(vals.values()) if done else None,
                                "endpoint_updates": ups, "costs_gpu_seconds": costs,
                                "staged275_minus_this": contrast(staged275, vals, seeds, f"Staged@275 - {arm}@B")}
        out[cohort] = res
        name = NAMES[cohort] + (f" ($B$={B / 3600:.1f} GPU-h)" if B else " ($B$ \\pending{X2})")
        st = x1.get(cohort, {}).get("means", {}).get("staged")
        lines.append(f"{name} & Staged @275 & {fmt_pct(pct(st), 'X2')} & 275 & -- \\\\")
        for arm, r in res["arms"].items():
            ups = [u for u in r["endpoint_updates"] if u is not None]
            cs = [c for c in r["costs_gpu_seconds"] if c is not None]
            complete = r["mean"] is not None
            lines.append(f" & {arm.replace('@B', '')} @$B$ & {fmt_pct(pct(r['mean']), 'X2')} & "
                         f"{(f'{mean(ups):.0f}' if complete and ups else chr(92) + 'pending{X2}')} & "
                         f"{(f'{mean(cs) / 3600:.1f}' if complete and len(cs) == len(seeds) else chr(92) + 'pending{X2}')} \\\\")
            lines.append(f" & \\quad Staged@275 $-$ this & \\multicolumn{{3}}{{l}}{{{fmt_delta(r['staged275_minus_this'], 'X2')}}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return out, "\n".join(lines)


# ------------------------------------------------------------------ X3
def x3_tables(x1, items):
    seeds = [5, 6, 7, 8, 9]
    v400 = {a: {s: None for s in seeds} for a in ("alignment", "sr", "staged")}
    for i in items:
        if i.get("arm") in v400 and i["key"].endswith(".eval") and i["state"] == "done":
            v400[i["arm"]][i["seed"]] = i.get("value")
    v275 = {a: x1.get("olmo_math", {}).get("per_seed", {}).get(a, {s: None for s in seeds}) for a in v400}
    res = {"seeds": seeds, "at_275": v275, "at_400": v400,
           "means_275": {a: mean(v.values()) if all(x is not None for x in v.values()) else None for a, v in v275.items()},
           "means_400": {a: mean(v.values()) if all(x is not None for x in v.values()) else None for a, v in v400.items()},
           "staged_minus_sr_400": contrast(v400["staged"], v400["sr"], seeds, "Staged - SR @400"),
           "staged_minus_alignment_400": contrast(v400["staged"], v400["alignment"], seeds, "Staged - Alignment @400"),
           "staged_minus_sr_275": contrast(v275["staged"], v275["sr"], seeds, "Staged - SR @275"),
           "staged_minus_alignment_275": contrast(v275["staged"], v275["alignment"], seeds, "Staged - Alignment @275")}
    lines = [PREAMBLE, "% X3: OLMo MATH seeds 5--9, the 275 states continued with a fixed update count to 400",
             "\\begin{tabular}{lrrll}", "\\toprule",
             "Horizon & Alignment & SR & Staged$-$SR & Staged$-$Alignment \\\\", "\\midrule"]
    for T, m, a, b in ((275, res["means_275"], res["staged_minus_sr_275"], res["staged_minus_alignment_275"]),
                       (400, res["means_400"], res["staged_minus_sr_400"], res["staged_minus_alignment_400"])):
        lines.append(f"{T} & {fmt_pct(pct(m['alignment']), 'X3')} & {fmt_pct(pct(m['sr']), 'X3')} & "
                     f"{fmt_delta(a, 'X3')} & {fmt_delta(b, 'X3')} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              f"% Staged mean: 275 {res['means_275']['staged']}, 400 {res['means_400']['staged']}", ""]
    return res, "\n".join(lines)



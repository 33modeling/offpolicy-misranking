def x4_tables(x1, items):
    seeds = list(env.X4_SEEDS)
    vals = {a: {s: None for s in seeds} for a in ("random", "sr", "alignment", "staged")}
    for i in items:
        if i.get("arm") in vals and i["key"].endswith(".eval") and i["state"] == "done":
            vals[i["arm"]][i["seed"]] = i.get("value")
    means = {a: mean(v.values()) if all(x is not None for x in v.values()) else None for a, v in vals.items()}
    res = {"seeds": seeds, "per_seed": vals, "means": means}
    for other in ("sr", "alignment", "random"):
        res[f"staged_minus_{other}"] = contrast(vals["staged"], vals[other], seeds, f"Staged - {other} (seeds 10-14)")
    old = x1.get("olmo_math", {}).get("per_seed", {})
    pooled_seeds = [5, 6, 7, 8, 9, *seeds]
    for other in ("sr", "alignment"):
        a = {**old.get("staged", {}), **vals["staged"]}
        b = {**old.get(other, {}), **vals[other]}
        res[f"pooled_staged_minus_{other}"] = contrast(a, b, pooled_seeds, f"Staged - {other} (seeds 5-14)")
    lines = [PREAMBLE, "% X4: OLMo MATH fresh seeds 10--14 (tau fixed from P0, no tuning); pooled = seeds 5--14",
             "\\begin{tabular}{lrrrr}", "\\toprule", "& Random & SR & Alignment & Staged \\\\", "\\midrule",
             "Mean reward (\\%) & " + " & ".join(fmt_pct(pct(means[a]), "X4") for a in ("random", "sr", "alignment", "staged"))
             + " \\\\", "\\midrule",
             f"Staged$-$SR (10--14) & \\multicolumn{{4}}{{l}}{{{fmt_delta(res['staged_minus_sr'], 'X4')}}} \\\\",
             f"Staged$-$Alignment (10--14) & \\multicolumn{{4}}{{l}}{{{fmt_delta(res['staged_minus_alignment'], 'X4')}}} \\\\",
             f"Staged$-$SR (5--14) & \\multicolumn{{4}}{{l}}{{{fmt_delta(res['pooled_staged_minus_sr'], 'X4')}}} \\\\",
             f"Staged$-$Alignment (5--14) & \\multicolumn{{4}}{{l}}{{{fmt_delta(res['pooled_staged_minus_alignment'], 'X4')}}} \\\\",
             "\\bottomrule", "\\end{tabular}", ""]
    return res, "\n".join(lines)



def x2_tables(x1, items):
    out = {}
    lines = [PREAMBLE, "% X2: equal compute. B = mean continuation cost of Staged (trajectory to tau + SR branch to 275). "
             "SR (and earlier switches) extended past 275 until B; Alignment stopped at its last snapshot within B.",
             "\\begin{tabular}{llrrr}", "\\toprule",
             "Cohort & Arm & Reward (\\%) & Mean update & Mean cost (GPU-h) \\\\", "\\midrule"]
    for cohort in env.X2_COHORTS:
        its = [i for i in items if i["cohort"] == cohort]
        B = next((i.get("value") for i in its if i["key"] == "budget" and i["state"] == "done"), None)
        seeds = [5, 6, 7, 8, 9]
        arms = {}
        for i in its:
            if i.get("arm") and "@B" in i["key"] and not i["key"].endswith(".train"):
                arms.setdefault(i["arm"], {})[i["seed"]] = i
        staged275 = x1.get(cohort, {}).get("per_seed", {}).get("staged", {s: None for s in seeds})
        res = {"budget_gpu_seconds": B, "arms": {}}
        for arm, by in sorted(arms.items()):
            vals = {s: by[s].get("value") if s in by and by[s]["state"] == "done" else None for s in seeds}
            done = all(v is not None for v in vals.values())
            ups = [by[s].get("endpoint_update") for s in seeds if s in by]
            costs = [by[s].get("cost") for s in seeds if s in by]
            res["arms"][arm] = {"per_seed": vals, "mean": mean(vals.values()) if done else None,
                                "endpoint_updates": ups, "costs_gpu_seconds": costs,
                                "staged275_minus_this": contrast(staged275, vals, seeds, f"Staged@275 - {arm}@B")}
        out[cohort] = res
        name = NAMES[cohort] + (f" ($B$={B / 3600:.1f} GPU-h)" if B else " ($B$ \\pending{X2})")
        st = x1.get(cohort, {}).get("means", {}).get("staged")
        lines.append(f"{name} & Staged @275 & {fmt_pct(pct(st), 'X2')} & 275 & -- \\\\")
        for arm, r in res["arms"].items():
            ups = [u for u in r["endpoint_updates"] if u is not None]
            cs = [c for c in r["costs_gpu_seconds"] if c is not None]
            complete = r["mean"] is not None
            lines.append(f" & {arm.replace('@B', '')} @$B$ & {fmt_pct(pct(r['mean']), 'X2')} & "
                         f"{(f'{mean(ups):.0f}' if complete and ups else chr(92) + 'pending{X2}')} & "
                         f"{(f'{mean(cs) / 3600:.1f}' if complete and len(cs) == len(seeds) else chr(92) + 'pending{X2}')} \\\\")
            lines.append(f" & \\quad Staged@275 $-$ this & \\multicolumn{{3}}{{l}}{{{fmt_delta(r['staged275_minus_this'], 'X2')}}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return out, "\n".join(lines)



def x2_extra(tau, x2, costs):
    """X2.text / X2.cost inputs: mean reward at B per switch time (best tau at B) and Staged cost against
    Alignment and SR over the incremental scope."""
    res, lines = {}, []
    for cohort, r in x2.items():
        by_tau = {}
        for arm, a in r["arms"].items():
            t = 25 if arm == "sr" else tau if arm == "staged" else int(arm[6:]) if arm.startswith("switch") else None
            if t is not None and a["mean"] is not None:
                by_tau[t] = a["mean"]
        best = max(by_tau, key=lambda t: (by_tau[t], -t)) if by_tau else None
        inc = {a: seed_mean(v["incremental"].get(a) for v in costs.get(cohort, {}).values())
               for a in ("alignment", "sr", "staged")}
        ratio = {a: (100.0 * inc["staged"] / inc[a]) if inc["staged"] is not None and inc[a] else None
                 for a in ("alignment", "sr")}
        res[cohort] = {"mean_reward_at_B_by_tau": {str(t): v for t, v in sorted(by_tau.items())},
                       "best_tau_at_B": best, "all_taus_at_B_measured": len(by_tau) == len(
                           [a for a in r["arms"] if a == "sr" or a == "staged" or a.startswith("switch")]),
                       "incremental_gpu_seconds": inc, "staged_cost_percent_of": ratio}
        lines.append(f"% {cohort}: mean reward at B by tau: " +
                     (", ".join(f"{t} {100 * v:.2f}" for t, v in sorted(by_tau.items())) or "pending") +
                     f"; best tau at B: {best if best is not None else 'pending'}")
        lines.append(f"% {cohort}: Staged incremental cost = " +
                     ", ".join(f"{'pending' if v is None else f'{v:.1f}%'} of {a}" for a, v in ratio.items()) +
                     (f"; B = {r['budget_gpu_seconds'] / 3600:.2f} GPU-h" if r.get("budget_gpu_seconds") else ""))
    return res, "\n".join(lines) + "\n"


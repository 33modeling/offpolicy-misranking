def tau_table(rec):
    taus = rec["candidate_taus"]
    lines = [PREAMBLE, f"% tau sweep, OLMo MATH Branch Bank seeds 5--9 (development cohort). Rule: {rec['rule']}",
             "\\begin{tabular}{l" + "r" * len(taus) + "}", "\\toprule",
             "$\\tau$ & " + " & ".join(str(t) for t in taus) + " \\\\", "\\midrule"]
    for basis, means in ((rec["basis"], rec["mean_reward_fraction_by_tau"]), (rec["other_basis"], rec["other_basis_means"])):
        cells = []
        for t in taus:
            v = None if means is None else means.get(str(t))
            cell = fmt_pct(pct(v), "P0")
            if basis == rec["basis"] and t == rec["tau"]:
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        label = {"equal_budget": "equal budget (V8 $B$)", "matched_update": "matched update 275"}[basis]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", f"% selected tau = {rec['tau']} (basis {rec['basis']})", ""]
    return "\n".join(lines)



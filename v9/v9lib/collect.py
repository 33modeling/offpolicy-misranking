PREAMBLE = ("% generated by v9/v9lib/collect.py from recorded outputs; do not edit by hand\n"
            "\\providecommand{\\pending}[1]{\\textcolor{red}{pending}}\n")


def paper_dir():
    return env.v9_root() / "paper"


def pct(x):
    return None if x is None else 100.0 * x


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def contrast(a, b, seeds, label):
    """Paired Staged - other over the cohort's seeds; complete only when every seed is measured."""
    from switching.analyze import paired
    r = paired(a, b, seeds, label=label)
    r["status"] = "measured" if not r["missing_seeds"] and r["n_training_seeds"] >= 2 else "pending"
    return r


def fmt_pct(x, tag):
    return f"\\pending{{{tag}}}" if x is None else f"{x:.2f}"


def fmt_delta(r, tag):
    if r is None or r.get("status") != "measured":
        n = 0 if r is None else r.get("n_training_seeds", 0)
        return f"\\pending{{{tag}}}" + (f" (n={n})" if n else "")
    lo, hi = r["ci_low"], r["ci_high"]
    return (f"{r['mean_delta_pp']:+.2f} [{lo:+.2f}, {hi:+.2f}] "
            f"({r['wins']}/{r['ties']}/{r['losses']})")


def write(name, text):
    from switching.common import atomic_write_text
    p = paper_dir() / name
    p.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(p, text)
    return p



NAMES = {"olmo_math": "OLMo-3 7B / MATH", "olmo_mbpp": "OLMo-3 7B / MBPP", "qwen_math": "Qwen3.5 9B / MATH",
         "qwen_mbpp": "Qwen3.5 9B / MBPP", "llama_math": "Llama-3.1 8B / MATH", "llama_mbpp": "Llama-3.1 8B / MBPP"}
